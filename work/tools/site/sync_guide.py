def fold_sources(lines):
    out = []
    for ln in lines:
        m = re.match(r'^\*Source(s)?:\*\s*(.*)$', ln)
        if m:
            out += ['<details class="tech" data-pagefind-ignore="all"><summary>Technical source (script files and flags)</summary>', '',
                    m.group(2), '', '</details>']
        else:
            out.append(ln)
    return out


def escape_mdx(text):
    """Make generated Markdown safe for MDX without changing how it renders.

    MDX reads `{`/`}` as expressions and `<` as the start of JSX, and has no HTML comments. Outside code
    spans and fenced code: `{`, `}` and a `<` that doesn't open a tag are backslash-escaped, and HTML
    comments are dropped. The tags the generator writes (<section>, <p>, <a>, <span>, <details>,
    <summary>) are valid JSX; <summary> moves to its own line below <details>.
    """
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    out, fence = [], None
    for ln in text.split('\n'):
        m = re.match(r'^\s*(`{3,}|~{3,})', ln)
        if fence:
            out.append(ln)
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence):
                fence = None
            continue
        if m:
            fence = m.group(1)
            out.append(ln)
            continue
        # MDX reads a block tag followed by more on the same line as inline JSX: put <summary> on its own line
        m = re.match(r'^(\s*<details\b[^>]*>)(<summary>.*)$', ln)
        if m:
            out.append(m.group(1))
            ln = m.group(1)[:len(m.group(1)) - len(m.group(1).lstrip())] + m.group(2)
        parts = re.split(r'(`+[^`]*?`+)', ln)  # odd parts are code spans
        for i in range(0, len(parts), 2):
            parts[i] = re.sub(r'([{}])', r'\\\1', parts[i])
            parts[i] = re.sub(r'<(?![A-Za-z/])', r'\\<', parts[i])
        out.append(''.join(parts))
    return '\n'.join(out)


def strip_page_toc(lines):
    """Drop the chapter's back link and "Quests on this page" list: the site has its own navigation and contents."""
    out, i = [], 0
    while i < len(lines):
        ln = lines[i]
        if re.match(r'^\[← Guide index\]\(README\.md\)\s*$', ln):
            i += 1
            continue
        if ln.strip() == '**Quests on this page:**':
            i += 1
            while i < len(lines) and (lines[i].startswith('- ') or not lines[i].strip()):
                i += 1
            continue
        out.append(ln)
        i += 1
    return out


def gh_slug(s):
    """Heading id as Starlight (github-slugger) makes it, close enough to spot ids shared between pages."""
    s = s.strip().lower()
    s = re.sub(r'[^\w\- ]', '', s, flags=re.UNICODE)
    return s.replace(' ', '-')


def quest_headings(src):
    """(heading text, metadata) for every H2, metadata from a `<!-- quest: ... -->` line right below it."""
    lines = src.split('\n')
    out = []
    for i, ln in enumerate(lines):
        if ln.startswith('## '):
            meta = {}
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            m = META_RE.match(lines[j].strip()) if j < len(lines) else None
            if m:
                meta = parse_meta(m.group(1))
            out.append((ln[3:].strip(), meta))
    return out


def link_place(areas, h, meta):
    if 'places' in meta:
        names = [x.strip() for x in meta['places'].split(',') if x.strip() and x.strip().lower() != 'none']
        found = []
        for n in names:
            for a in ([areas.by_slug[n]] if n in areas.by_slug else areas.find_one(n)):
                if a not in found:
                    found.append(a)
        return found, True
    if ':' not in h:
        return [], False
    return areas.find_all(h.split(':')[0]), False


def validate_ledger(srcs, ledger=QUEST_LEDGER):
    """Fail before generation if identities, provenance or required edges are stale."""
    records = ledger['quests']
    ids = [q['id'] for q in records]
    if len(ids) != len(set(ids)):
        raise SystemExit('duplicate quest IDs in ledger')
    actual = {}
    for fn, src in srcs.items():
        if page_slug(fn) in PLAIN_PAGES:
            continue
        for heading, meta in quest_headings(src):
            identity = meta.get('id')
            if not identity or identity in actual:
                raise SystemExit('missing or duplicate stable quest ID: %s: %s' % (fn, heading))
            actual[identity] = 'guide/%s#%s' % (fn, gh_slug(heading))
    if set(actual) != set(ids):
        raise SystemExit('quest ledger coverage differs from guide IDs')
    legacy = set()
    graph = {}
    sources = set(actual.values())
    for q in records:
        if q['source'] != actual[q['id']] or q['stage'] not in ledger['stages']:
            raise SystemExit('stale source or unknown stage: %s' % q['id'])
        if q['review'] not in ('guide-reviewed', 'needs-review'):
            raise SystemExit('unknown review state: %s' % q['id'])
        if q.get('prototype') and (q['stage'] == 'unknown' or q['review'] != 'guide-reviewed'):
            raise SystemExit('unreviewed prototype: %s' % q['id'])
        for key in q['legacy_keys']:
            if key in legacy or not re.fullmatch(r'guide/[^/#]+#[^#]+', key):
                raise SystemExit('invalid or ambiguous legacy key: %s' % key)
            legacy.add(key)
        graph[q['id']] = []
        for edge in q['requires']:
            if edge['quest'] not in actual or edge['kind'] not in ('required', 'recommended', 'conditional', 'step') or edge['evidence'] not in sources:
                raise SystemExit('invalid prerequisite: %s' % q['id'])
            if edge['kind'] == 'required':
                graph[q['id']].append(edge['quest'])
        for gate in q.get('opens_after', []) + q['deadlines']:
            if gate['milestone'] not in ledger['milestones'] or gate['evidence'] not in sources:
                raise SystemExit('invalid milestone gate: %s' % q['id'])
        for warning in q['warnings']:
            if warning['evidence'] not in sources:
                raise SystemExit('invalid warning evidence: %s' % q['id'])
    for milestone in ledger['milestones'].values():
        if milestone['evidence'] not in sources:
            raise SystemExit('invalid milestone evidence')
    visiting, finished = set(), set()
    def visit(identity):
        if identity in visiting:
            raise SystemExit('cycle in required quest prerequisites: %s' % identity)
        if identity in finished:
            return
        visiting.add(identity)
        for dependency in graph[identity]:
            visit(dependency)
        visiting.remove(identity)
        finished.add(identity)
    for identity in graph:
        visit(identity)


def page_description(lines, prefix=''):
    """Search description for a plain guide page: its first prose paragraph, as plain text, about 160 characters."""
    for ln in lines:
        t = ln.strip()
        if not t or t[0] in '#[<|-!>*' and not t.startswith('**'):
            continue
        t = re.sub(r'!?\[([^\]]*)\]\([^)]*\)', r'\1', t)
        t = re.sub(r'[*_`]+', '', t)
        if prefix:
            t = prefix + t[0].lower() + t[1:]
        return clamp_description(t)
    return None


def clamp_description(t, limit=160):
    """At most `limit` characters, cut at a word boundary with an ellipsis."""
    if len(t) <= limit:
        return t
    t = t[:limit - 1]
    return t[:t.rfind(' ')].rstrip(',;:') + '…'


def convert(fn, src, areas, shared_ids=(), report=None, force_mdx=False, collect=None, link_map=None, unresolved=None):
    """(file name, text) of the site page for guide/<fn>: <slug>.mdx when it has solver markers, else <slug>.md."""
    lines = src.rstrip('\n').split('\n')
    title = None
    if lines and lines[0].startswith('# '):
        title = lines[0][2:].strip()
        lines = lines[1:]
    slug = page_slug(fn)
    depth = 0 if slug == 'index' else 1
    lines = strip_page_toc(lines)
    metas = iter([m for _, m in quest_headings('\n'.join(lines))])
    body, in_quest, pending_meta, solvers = [], False, False, []
    current = None  # (quest id, info dict, index in body where its <section> starts)

    def close_section():
        nonlocal current
        if current and collect is not None:
            qid, rec, start = current
            rec['lines'] = body[start:]
            collect[qid] = rec
        current = None
    for ln in fold_sources(lines):
        m = SOLVER_RE.match(ln)
        if m:
            name = m.group(2)
            if name not in SOLVERS:
                raise SystemExit('guide/%s: unknown solver %r (known: %s)' % (fn, name, ', '.join(sorted(SOLVERS))))
            if not in_quest:
                raise SystemExit('guide/%s: solver %r must sit inside a quest section (below an H2)' % (fn, name))
            solvers.append(name)
            body += ['', m.group(1) + SOLVER_SLOT % name, '']
            continue
        if pending_meta:
            if not ln.strip():
                continue
            pending_meta = False
            if META_RE.match(ln.strip()):
                continue
        if ln.startswith('## '):
            if in_quest:
                body += ['', '</section>', '']
                close_section()
            h = ln[3:].strip()
            meta = next(metas)
            where = 'guide/%s: %s' % (fn, h)
            tags = apply_meta(heading_tags(h), meta, where)
            if slug not in PLAIN_PAGES and 'kind' not in tags:
                raise SystemExit('%s: add quest metadata with kind=main or kind=side' % where)
            attrs = ['data-%s="%s"' % (k, html.escape(','.join(v) if isinstance(v, list) else v if isinstance(v, str) else 'yes', quote=True)) for k, v in sorted(tags.items())]
            if meta.get('id'):
                attrs.append('data-quest-id="%s"' % html.escape(meta['id'], quote=True))
                record = QUEST_RECORDS.get(meta['id'])
                if record:
                    extra = {'legacy-keys': json.dumps(record['legacy_keys'], ensure_ascii=False)}
                    prototype = record.get('prototype')
                    if prototype:
                        extra.update({'checklist-title': prototype['title'],
                                      'checklist-location': prototype['location'],
                                      'checklist-order': str(prototype['order']),
                                      'checklist-stage': record['stage'],
                                      'checklist-stage-label': QUEST_LEDGER['stages'][record['stage']],
                                      'checklist-notes': json.dumps([x['summary'] for x in record['deadlines'] + record['warnings']], ensure_ascii=False),
                                      'checklist-starter': ','.join(record['applicability'].get('starter', []))})
                    attrs.extend('data-%s="%s"' % (k, html.escape(v, quote=True)) for k, v in extra.items())
            if gh_slug(h) in shared_ids:
                attrs.append('data-legacy-shared="yes"')
            in_quest = slug not in PLAIN_PAGES
            if in_quest:
                current = (meta.get('id'), {'title': h, 'tags': tags, 'anchor': gh_slug(h), 'file': fn,
                                            'solvers': [], 'solver_start': len(solvers)}, len(body))
                body += ['<section class="quest" %s>' % ' '.join(attrs) if attrs else '<section class="quest">', '']
            body.append(ln)
            body.append('')
            pending_meta = True
            tagline = []
            if in_quest:
                found, explicit = link_place(areas, h, meta)
                for a in found:
                    tagline.append('<a class="tag tag-place" href="%s../locations/%s/">%s</a>' % ('../' * depth, a['slug'], a['name']))
                if not found and not explicit and report is not None and not h.startswith(NO_PLACE):
                    report.append('%s: %s' % (fn, h))
            badges = tag_badges(tags) if in_quest else ''
            if badges:
                tagline.append(badges)
            if tagline:
                body += ['<p class="quest-meta">%s</p>' % ' '.join(tagline), '']
            continue
        body.append(ln)
    if in_quest:
        body += ['', '</section>']
        close_section()
    if collect is not None:
        for rec in collect.values():
            if rec['file'] == fn:
                rec['solvers'] = [n for n in SOLVERS if any(SOLVER_SLOT % n in x for x in rec['lines'])]
    text = rewrite_links('\n'.join(body), depth, link_map, unresolved)
    text = re.sub(r'\n{3,}', '\n\n', text)
    fm = ['---', 'title: %s' % json.dumps(title or slug)]
    desc = page_description(lines, 'Origin HeartGold walkthrough: ' if slug == 'index' else '')
    if desc:
        fm += ['description: %s' % json.dumps(desc, ensure_ascii=False)]
    fm += ['sidebar:', '  order: %d' % page_order(fn)]
    if slug == 'index':
        fm += ['  label: Overview']
    if fn == 'known-issues.md':
        fm += ['  label: Known issues']
    if fn == 'hidden-items.md':
        fm += ['  label: Hidden items']
    fm += ['source: guide/%s' % fn, 'editUrl: false', '---', '']
    text = text.strip('\n') + '\n'
    if not (solvers or force_mdx):
        return page_slug(fn) + '.md', '\n'.join(fm) + text
    text = escape_mdx(text)
    comps = sorted({SOLVERS[n] for n in solvers})
    head = ['import %s from \'../../../components/%s.astro\';' % (c, c) for c in comps]
    head += ['', GEN_NOTE % fn, '']
    for n in solvers:
        text = text.replace(SOLVER_SLOT % n, '<%s />' % SOLVERS[n], 1)
    text = re.sub(r'\n{3,}', '\n\n', text)
    return page_slug(fn) + '.mdx', '\n'.join(fm) + '\n'.join(head) + text


def chapter_list(chapters):
    """Markdown list of the chapters for the guide index (links relative to /guide/)."""
    out = []
    for ch in chapters:
        out.append('- [%s](./%s/): %s (%d)' % (ch['title'], ch['id'], ch['summary'], len(ch['quests'])))
    return '\n'.join(out)


def hidden_item_sections(source):
    """Index the existing location guide, keeping its spot counts and screenshot caveats."""
    sections = {}
    for part in re.split(r'^## ', source, flags=re.M)[1:]:
        heading, _, body = part.partition('\n')
        count = len(re.findall(r'^\*Source:\* hidden-item event ', body, flags=re.M))
        if count:
            sections[heading.strip()] = {
                'anchor': gh_slug(heading), 'count': count,
                'missing': body.count('**Missing screenshot.**'),
                'body': body.strip('\n'),
            }
    return sections


def chapter_hidden_areas(ch, sections):
    """The chapter's hidden-item locations in full (directions and pictures), one section per location, for the
    phone layout: site/public/ohg.js moves each under the walkthrough step that visits the place. Wider screens never
    show them (they keep the disclosure's links), so they stay out of the search index. The *Source:* lines are technical
    and stay on the hidden-items page."""
    names = ch.get('hidden_items', [])
    if not names:
        return []
    out = ['<div class="chapter-hidden-areas" data-pagefind-ignore="all" hidden>', '']
    for name in names:
        entry = sections[name]
        body = re.sub(r'^\*Source:\*.*\n?', '', entry['body'], flags=re.M).strip('\n')
        body = re.sub(r'\n{3,}', '\n\n', body)
        out += ['<section class="chapter-hidden-area" data-area="%s" data-spots="%d" data-anchor="%s">' % (
            html.escape(name), entry['count'], entry['anchor']), '', body, '', '</section>', '']
    out += ['</div>', '']
    return out


def chapter_hidden_items(ch, sections):
    """A native disclosure: optional location links, with no item spoilers while closed."""
    names = ch.get('hidden_items', [])
    if not names:
        return []
    if len(names) != len(set(names)) or any(name not in sections for name in names):
        raise SystemExit('%s: hidden_items must name unique locations from guide/hidden-items.md' % ch['_file'])
    out = ['<details class="chapter-hidden-items">',
           '<summary>Hidden items along the way</summary>', '',
           'Optional stops in this chapter’s locations. Some spots may need a return visit; check the location notes for access limitations.', '',
           'Open a location for item names, directions and available screenshots.', '']
    for name in names:
        entry = sections[name]
        count = entry['count']
        label = '%s — %d %s' % (name, count, 'spot' if count == 1 else 'spots')
        note = ' (%d without screenshots)' % entry['missing'] if entry['missing'] else ''
        out.append('- [%s](hidden-items.md#%s)%s' % (label, entry['anchor'], note))
    out += ['', '[Browse all hidden items](hidden-items.md)', '', '</details>', '']
    return out


def build_chapter_page(ch, collect, chapter_of, link_map, unresolved, force_mdx=False):
    """(file name, text) of the site page for one chapter."""
    info = collect
    sections, solvers = {}, []
    for q in ch['quests']:
        rec = collect[q['id']]
        lines = list(rec['lines'])
        notes = []
        if q.get('available_note'):
            notes.append(q['available_note'].strip())
        if q.get('level_note'):
            notes.append(q['level_note'].strip())
        if q.get('needs'):
            notes.append('Do first: ' + ', '.join(chapters_mod.quest_link(n, info, chapter_of, ch['id']) for n in q['needs']) + '.')
        if notes:
            # after the heading and its tag line
            i = next(k for k, x in enumerate(lines) if x.startswith('## '))
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            if j < len(lines) and lines[j].startswith('<p class="quest-meta">'):
                j += 1
            lines[j:j] = ['', '<p class="quest-note">%s</p>' % ' '.join(notes), '']
        if q.get('missable') and 'data-missable' not in lines[0]:
            raise SystemExit('%s: %s is missable in the chapter but the section has no missable tag' % (ch['_file'], q['id']))
        # "[...](#some-quest)" links inside a quest body: that quest may now sit in another chapter
        def local(m, fn=rec['file']):
            target = link_map.get((fn, m.group(1)))
            if target is None or target == ch['id']:
                return m.group(0)
            return '](../%s/#%s)' % (target, m.group(1))
        lines = [re.sub(r'\]\(#([^)\s]+)\)', local, x) for x in lines]
        sections[q['id']] = lines
        solvers += rec['solvers']
    with open(os.path.join(GUIDE, 'hidden-items.md'), encoding='utf-8') as fh:
        hidden_sections = hidden_item_sections(fh.read())
        hidden = chapter_hidden_items(ch, hidden_sections) + chapter_hidden_areas(ch, hidden_sections)
    body = chapters_mod.render_chapter(ch, collect, chapter_of, sections, None, None, hidden_items=hidden)
    text = rewrite_links('\n'.join(body), 1, link_map, unresolved)
    text = re.sub(r'\n{3,}', '\n\n', text)
    order = 10 + ch['order']
    fm = ['---', 'title: %s' % json.dumps(ch['title'], ensure_ascii=False), 'description: %s' % json.dumps(clamp_description('Origin HeartGold walkthrough, chapter %d: %s' % (ch['order'], ch['summary'])), ensure_ascii=False),
          'sidebar:', '  order: %d' % order, '  label: %s' % json.dumps(chapters_mod.short_label(ch), ensure_ascii=False),
          'source: guide/chapters/%s' % ch['_file'], 'editUrl: false', '---', '']
    text = text.strip('\n') + '\n'
    if not (solvers or force_mdx):
        return ch['id'] + '.md', '\n'.join(fm) + text
    text = escape_mdx(text)
    comps = sorted({SOLVERS[n] for n in solvers})
    head = ["import %s from '../../../components/%s.astro';" % (c, c) for c in comps]
    head += ['', GEN_NOTE % ('chapters/' + ch['_file']), '']
    for n in dict.fromkeys(solvers):
        text = text.replace(SOLVER_SLOT % n, '<%s />' % SOLVERS[n])
    text = re.sub(r'\n{3,}', '\n\n', text)
    return ch['id'] + '.mdx', '\n'.join(fm) + '\n'.join(head) + text


def legacy_map(srcs, collect, chapter_of):
    """Old region page slug -> {default chapter, anchors}: lets /guide/<old>/#anchor forward to the right chapter."""
    out = {}
    for fn in sorted(srcs):
        slug = page_slug(fn)
        if slug in PLAIN_PAGES:
            continue
        ids = [qid for qid, r in collect.items() if r['file'] == fn]
        if not ids:
            continue
        ids.sort(key=lambda q: chapter_of[q])
        out[slug] = {'default': chapter_of[ids[0]],
                     'anchors': {collect[q]['anchor']: chapter_of[q] for q in ids}}
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--unmatched', action='store_true', help='list quest headings with no location link')
    ap.add_argument('--all-mdx', action='store_true', help='test the MDX escaping: write every page as .mdx')
    a = ap.parse_args(argv)
    aliases = json.load(open(ALIASES, encoding='utf-8')) if os.path.exists(ALIASES) else {}
    areas = AreaIndex(json.load(open(AREAS, encoding='utf-8')), aliases)
    srcs = {}
    for fn in sorted(os.listdir(GUIDE)):
        if fn.endswith('.md'):
            srcs[fn] = open(os.path.join(GUIDE, fn), encoding='utf-8').read()
    validate_ledger(srcs)
    # Heading ids used on more than one quest page. Old "Done" ticks were stored by bare heading id,
    # so a tick on one of these can't be told apart and is not carried over (see site/public/ohg.js).
    pages_of, quest_ids = {}, {}
    for fn, src in srcs.items():
        if page_slug(fn) in PLAIN_PAGES:
            continue
        for h, meta in quest_headings(src):
            pages_of.setdefault(gh_slug(h), set()).add(fn)
            if meta.get('id'):
                quest_ids.setdefault(meta['id'], []).append('%s: %s' % (fn, h))
    dup = {k: v for k, v in quest_ids.items() if len(v) > 1}
    if dup:
        raise SystemExit('duplicate quest ids in <!-- quest: id=... -->: %s' % dup)
    shared = LEGACY_SHARED_IDS | {k for k, v in pages_of.items() if len(v) > 1}
    want, report = {}, []
    chapters = chapters_mod.load()
    ledger_ids = {q['id'] for q in QUEST_LEDGER['quests']}
    collect, unresolved = {}, []
    # pass 1: the quest files only give up their quest sections (they are not pages any more)
    for fn, src in srcs.items():
        if page_slug(fn) not in PLAIN_PAGES:
            convert(fn, src, areas, shared, report, a.all_mdx, collect=collect)
    missable_ids = {qid for qid, r in collect.items() if r['tags'].get('missable')}
    errors = chapters_mod.validate(chapters, ledger_ids, missable_ids)
    if errors:
        raise SystemExit('guide/chapters: %d problems, first ones:\n  ' % len(errors) + '\n  '.join(errors[:15]))
    chapter_of = {q['id']: ch['id'] for ch in chapters for q in ch['quests']}
    link_map = {}
    first_of_file = {}
    for ch in chapters:
        for q in ch['quests']:
            rec = collect[q['id']]
            link_map[(rec['file'], rec['anchor'])] = ch['id']
            first_of_file.setdefault(rec['file'], ch['id'])
    for fn, ch_id in first_of_file.items():
        link_map[(fn, None)] = ch_id
    # pass 2: pages that stay (index, known issues, hidden items) with links to the chapter pages
    for fn, src in srcs.items():
        if page_slug(fn) in PLAIN_PAGES:
            name, text = convert(fn, src, areas, shared, report, a.all_mdx, link_map=link_map, unresolved=unresolved)
            if page_slug(fn) == 'index':
                text = text.replace(CHAPTER_LIST_MARKER, chapter_list(chapters))
            want[name] = text
    for ch in chapters:
        name, text = build_chapter_page(ch, collect, chapter_of, link_map, unresolved, a.all_mdx)
        want[name] = text
    # quest bodies link to each other: every such link must land on a chapter page
    if unresolved:
        raise SystemExit('guide links that match no quest heading (fix the anchor in the guide):\n  ' + '\n  '.join(sorted(set(unresolved))))
    legacy = legacy_map(srcs, collect, chapter_of)
    legacy_text = json.dumps(legacy, indent=1, ensure_ascii=False, sort_keys=True) + '\n'
    legacy_old = open(LEGACY_PATH, encoding='utf-8').read() if os.path.exists(LEGACY_PATH) else None
    if legacy_old != legacy_text and not a.check:
        os.makedirs(os.path.dirname(LEGACY_PATH), exist_ok=True)
        with open(LEGACY_PATH, 'w', encoding='utf-8') as fh:
            fh.write(legacy_text)
    if a.unmatched:
        for r in report:
            print('no location link: ' + r)
        print('%d quest headings without a location link' % len(report))
    changed = []
    existing = set(os.listdir(OUT)) if os.path.isdir(OUT) else set()
    for name, text in sorted(want.items()):
        path = os.path.join(OUT, name)
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != text:
            changed.append(name)
            if not a.check:
                os.makedirs(OUT, exist_ok=True)
                with open(path + '.tmp', 'w', encoding='utf-8') as fh:
                    fh.write(text)
                os.replace(path + '.tmp', path)
    stale = sorted(n for n in existing if n.endswith(('.md', '.mdx')) and n not in want)
    for n in stale:
        changed.append(n + ' (stale)')
        if not a.check:
            os.remove(os.path.join(OUT, n))
    changed += sync_images(a.check)
    for c in changed:
        print(('would change: ' if a.check else 'wrote: ') + 'site/src/content/docs/guide/' + c)
    print('%d guide pages, %d changed' % (len(want), len(changed)))
    return 1 if (a.check and changed) else 0


if __name__ == '__main__':
    sys.exit(main())
