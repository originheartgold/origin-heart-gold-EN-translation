_LISTS = {}


def reviewed(name):
    """{id: entry} of the reviewed list work/tools/site/<name>.json."""
    if name not in _LISTS:
        path = os.path.join(R.REPO, 'work', 'tools', 'site', name + '.json')
        _LISTS[name] = {e['id']: e for e in R.read_json(path)['entries']}
    return _LISTS[name]


# Evolution methods whose parameter is an item. An item a player can never get makes those evolutions impossible too.
ITEM_EVO = {6, 7, 16, 17, 18, 19, 37}


def items_not_in_game():
    return reviewed('items_not_in_game')


def evo_works(m, p):
    """The evolution can happen in this game: the code checks the method and any item it needs exists."""
    return evo_possible(m) and not (m in ITEM_EVO and p in items_not_in_game())


def full_names(_cat=None):
    """In-game (shortened) spelling -> full official name, from the glossary's abbreviation tables
    (work/glossary/manual_overrides.py ABBREV and work/tools/fill_names.py LOCAL_ABBREV). The banks keep
    the short spelling the game's name buffers need; reference pages show the full name."""
    import ast
    rev = {}
    for path, var in ((os.path.join(R.REPO, 'work', 'glossary', 'manual_overrides.py'), 'ABBREV'),
                      (os.path.join(R.REPO, 'work', 'tools', 'fill_names.py'), 'LOCAL_ABBREV')):
        try:
            tree = ast.parse(open(path, encoding='utf-8').read())
        except OSError:
            continue
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(getattr(t, 'id', None) == var for t in node.targets):
                for full, short in ast.literal_eval(node.value).items():
                    short = re.sub(r' \(.*\)$', '', short)
                    if short == full or short in full.split() or full.endswith(' ' + short):
                        continue          # form names whose in-game name is just the base species
                    if short not in rev or len(full) < len(rev[short]):
                        rev[short] = full
    return rev


def md_escape(s):
    return str(s).replace('|', '\\|')


def clean_name(s):
    return (s or '').replace('₧₦', 'PKMN').replace('{NEWLINE}', ' ')


def anchor(s):
    s = s.lower()
    s = re.sub(r'[^a-z0-9 \-]', '', s)
    return s.replace(' ', '-')


class Ctx:
    def __init__(self, rom=None):
        self.rom = rom or R.Rom()
        r = self.rom
        self.SP = {k: clean_name(v) for k, v in R.load_bank(232).items()}
        self.MV = {k: clean_name(v) for k, v in R.load_bank(739).items()}
        self.IT = {k: clean_name(v) for k, v in R.load_bank(219).items()}
        self.AB = {k: clean_name(v) for k, v in R.load_bank(711).items()}
        self.TY = R.load_bank(724)
        self.TRN = {k: clean_name(v) for k, v in R.load_bank(719).items()}
        self.TRC = {k: clean_name(v) for k, v in R.load_bank(720).items()}
        self.TRADE_NAMES = {k: clean_name(v) for k, v in R.load_bank(198).items()}
        self.personal = [R.parse_personal(b) for b in r['personal']]
        self.learn = [R.parse_learnset(b) for b in r['learnset']]
        self.evos = [R.parse_evos(b) for b in r['evo']]
        self.compat = [set(R.parse_idlist(b)) for b in r['compat']]
        self.eggmoves = [R.parse_idlist(b) for b in r['eggmoves']]
        self.moves = [R.parse_move(b) for b in r['moves']]
        self.items = [R.parse_item(b) for b in r['item']]
        self.tm = R.parse_tm_table(r.arm9)
        self.tm_sorted = sorted(self.tm, key=lambda i: (i >= R.ITEM_HM01 and i <= R.ITEM_HM08, R.tm_label(i)[:2], int(R.tm_label(i)[2:])))
        self.forms = {}
        for sp, form, tgt in R.parse_form_table(r.arm9):
            self.forms[tgt] = (sp, form)
        self.FORM_NAMES = {k: v for k, v in R.read_json(FORM_NAMES).items() if not k.startswith('_')} \
            if os.path.exists(FORM_NAMES) else {}
        self.FULL = self.FULL_SP = full_names()
        bm = R.read_json(os.path.join(R.REPO, 'work', 'translate', 'bank_maps.json'))
        self.zones = bm['_zones']
        self.file_zones = collections.defaultdict(list)
        for z in self.zones:
            self.file_zones[z['scripts_bank']].append(z['zone_id'])
        names = collections.Counter(self._zbase(z) for z in self.zones)
        self._dup = {n for n, c in names.items() if c > 1}
        overrides = {}
        if os.path.exists(PLACE_NAMES):
            overrides = {k: v for k, v in R.read_json(PLACE_NAMES).items() if not k.startswith('_')}
        po = R.read_json(os.path.join(R.REPO, 'work', 'translate', 'play_order.json'))
        self.mapsec_rank = {}
        for _phase, secs in po['story_mapsecs']:
            for s in secs:
                self.mapsec_rank.setdefault(s, len(self.mapsec_rank))
        self.S = R.index_scripts(r['scripts'])
        std = {lo: f for lo, f, _m in r.std_mapping()}
        self.ball_file = std[7000]       # item-ball std scripts (7000+n), file 141
        self.std_file = std[2000]        # common std scripts (2000+n), file 3
        self.events = {}
        for z in self.zones:
            b = z['events_bank']
            if b not in self.events:
                try:
                    self.events[b] = R.parse_events(r['events'][b])
                except Exception:
                    self.events[b] = dict(bg=[], obj=[], warp=[], coord=[])
        self.places = places.PlaceNamer(self.zones, self.events, self._zbase, overrides)
        self.findings = []   # (key, text) data oddities for the cross-reference

    # ---- names
    def sp(self, i, form=0):
        if form and i not in self.forms:
            i = form_index(self, i, form)
            if i in self.forms:
                form = 0
        if i in self.forms:
            if str(i) in self.FORM_NAMES:
                return self.FORM_NAMES[str(i)]
            base, f = self.forms[i]
            return '%s (form %d)' % (self.full_sp(base), f)
        n = self.full_sp(i)
        return n + (' (form %d)' % form if form else '')

    def full_sp(self, i):
        """Species name, with the full spelling where the game's 10-character buffer cuts it."""
        n = self.SP.get(i) or '#%d' % i
        return self.FULL_SP.get(n, n)

    def mv(self, m):
        n = self.MV.get(m)
        return self.FULL.get(n, n) if n else 'move #%d' % m

    def it(self, i):
        lab = R.tm_label(i)
        if lab and i in self.tm:
            return '%s %s' % (lab, self.mv(self.tm[i]))
        n = self.IT.get(i)
        return self.FULL.get(n, n) if n else 'item #%d' % i

    def ab(self, a):
        n = self.AB.get(a)
        if n:
            return self.FULL.get(n, n)
        return '—' if not a else 'unnamed ability #%d (the game has no name text for it)' % a

    def ty(self, t):
        return R.TYPES[t] if 0 <= t < len(R.TYPES) else 'type #%d' % t

    def _zbase(self, z):
        return z['map_name_en'] or z.get('vanilla_map_name_en') or z['vanilla_const']

    def zname(self, zid):
        z = self.zones[zid]
        o = self.places.overrides.get(str(zid))
        if o:
            return o                          # hand correction (work/docs/place_names.json)
        n = self._zbase(z)
        if n in self._dup or n == 'Mystery Zone':
            return self.places.label(zid)     # "Celadon Game Corner", not a map number
        return n

    def zrank(self, zid):
        z = self.zones[zid]
        return (self.mapsec_rank.get(z['mapsec'], 10000), self._zbase(z), zid)

    def file_places(self, f):
        zs = sorted(set(self.file_zones.get(f, [])), key=self.zrank)
        return [self.zname(z) for z in zs]

    def place_str(self, f):
        p = self.file_places(f)
        if not p:
            return 'script file %d (no map)' % f
        p2 = list(dict.fromkeys(p))
        return ', '.join(p2[:3]) + (' …' if len(p2) > 3 else '')

    # ---- species helpers
    def species_ids(self):
        return [i for i in range(1, len(self.personal)) if sum(self.personal[i]['stats'])]

    def can_learn_tm(self, sp, move):
        if sp == EGG_SPECIES:
            return False
        if move == RETURN or sp == MEW:
            return True
        if move in self.compat[sp]:
            return True
        return any(m == move for _, m in self.learn[sp])


# ======================================================================== moves
def move_row(ctx, m):
    d = ctx.moves[m] if m < len(ctx.moves) else None
    if not d:
        return ['?'] * 5
    cat = ['Status', 'Physical', 'Special'][d['category']] if d['category'] < 3 else '?'
    pw = str(d['power']) if d['power'] > 1 else ('—' if d['power'] == 0 else 'var.')
    acc = '—' if d['accuracy'] in (0, 101) else str(d['accuracy'])
    return [ctx.ty(d['type']), cat, pw, acc, str(d['pp'])]


def gen_moves(ctx):
    out = [GEN_NOTE, '# Moves\n',
           'Move data as the game reads it: `extra/new_move_data.narc` (NARC 276), not the stale `a/0/1/1`. '
           'Power "var." means the power is computed in battle (e.g. Flail); "—" accuracy means it never misses '
           'or has no accuracy check.\n',
           '| # | Move | Type | Category | Power | Acc. | PP | TM/HM |', '|---|---|---|---|---|---|---|---|']
    tm_of = collections.defaultdict(list)
    for i, m in ctx.tm.items():
        tm_of[m].append(R.tm_label(i))
    for m in range(1, len(ctx.moves)):
        out.append('| %d | %s | %s | %s |' % (m, md_escape(ctx.mv(m)), ' | '.join(move_row(ctx, m)),
                                             ', '.join(sorted(tm_of.get(m, [])))))
    out.append('\n## TM and HM list\n')
    out.append('| TM | Move | Type | Category | Power | Acc. | PP |')
    out.append('|---|---|---|---|---|---|---|')
    for i in ctx.tm_sorted:
        out.append('| %s | %s | %s |' % (R.tm_label(i), md_escape(ctx.mv(ctx.tm[i])), ' | '.join(move_row(ctx, ctx.tm[i]))))
    return '\n'.join(out) + '\n'


# ======================================================================== pokemon
def gender_text(g):
    if g == 255:
        return 'genderless'
    if g == 0:
        return 'always male'
    if g == 254:
        return 'always female'
    return '%.1f%% female' % (100.0 * (g + 1) / 256)


def evo_text(ctx, m, p):
    fmt = dict(p=p, item=ctx.it(p), move=ctx.mv(p), species=ctx.sp(p), type=ctx.ty(p) if p < 18 else p)
    if m in EVO_TEXT:
        return EVO_TEXT[m].format(**fmt)
    return 'not possible in this game (official games: %s)' % NEVER_EVO.get(m, 'method %d' % m).format(**fmt)


