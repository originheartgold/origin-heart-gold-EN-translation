def species_chains(ins):
    """Runs of CompareVarToValue(var, species) + GoToIf(==) in a script: tutor species lists."""
    pcs = sorted(ins)
    chains = []
    cur = None
    for pc in pcs:
        op, a, n, t = ins[pc]
        if op == 17 and n in ins and ins[n][0] == 28 and ins[n][1][0] == 1:
            if cur and cur['var'] == a[0] and cur['next'] == pc:
                cur['species'].append(a[1])
                cur['next'] = ins[n][2]
            else:
                if cur and len(cur['species']) >= 3:
                    chains.append(cur)
                cur = dict(start=pc, var=a[0], species=[a[1]], next=ins[n][2])
    if cur and len(cur['species']) >= 3:
        chains.append(cur)
    return chains


def reach_owner(d):
    """pc -> set of entry indexes that reach it."""
    ins = d['ins']
    owner = collections.defaultdict(set)
    for ei, e in enumerate(d['entries']):
        st, seen = [e], set()
        while st:
            pc = st.pop()
            if pc in seen or pc not in ins:
                continue
            seen.add(pc)
            owner[pc].add(ei)
            op, a, n, t = ins[pc]
            if t is not None:
                st.append(t)
            if not (op in R.TERM or (op in R.JUMPS and R.JUMPS[op])):
                st.append(n)
    return owner


def cost_of(ctx, d, owner, target_pcs, lo, hi):
    ents = set()
    for pc in target_pcs:
        ents |= owner.get(pc, set())
    cost = []
    for r in d['recs']:
        if not (lo <= r['pc'] < hi) or not (owner.get(r['pc'], set()) & ents):
            continue
        if r['kind'] == 'item_take' and r['args'][0]:
            cost.append('%s ×%s' % (ctx.it(r['args'][0]), r['args'][1] if r['args'][1] is not None else '?'))
        elif r['kind'] == 'money_take' and r['args'][0]:
            cost.append('₽%d' % r['args'][0])
        elif r['kind'] == 'coins_take' and r['args'][0]:
            cost.append('%d coins' % r['args'][0])
    return list(dict.fromkeys(cost))


def cost_after(ctx, d, pcs, stop_moves, limit=60):
    """Payments reached by following the script forward from the teaching command(s) until
    the script ends or returns (tutors that teach first and charge in a shared block reached
    by GoTo, e.g. the Saffron Dojo). Stops at a has/set of another move."""
    recs = {r['pc']: r for r in d['recs']}
    ins = d['ins']
    cost, seen = [], set()
    todo = [(ins[pc][2], 0) for pc in pcs if pc in ins]
    while todo:
        pc, n = todo.pop()
        while pc in ins and pc not in seen and n < limit:
            seen.add(pc)
            n += 1
            op, a, nxt, tgt = ins[pc]
            r = recs.get(pc)
            if r:
                if r['kind'] in ('set_move', 'has_move'):
                    mv = r['args'][2] if r['kind'] == 'set_move' else r['args'][1]
                    if mv in stop_moves:
                        break
                if r['kind'] == 'item_take' and r['args'][0]:
                    cost.append('%s ×%s' % (ctx.it(r['args'][0]), r['args'][1] if r['args'][1] is not None else '?'))
                elif r['kind'] == 'money_take' and r['args'][0]:
                    cost.append('₽%d' % r['args'][0])
                elif r['kind'] == 'coins_take' and r['args'][0]:
                    cost.append('%d coins' % r['args'][0])
            if op in (2, 27):          # End, Return
                break
            if op == 22:               # GoTo
                pc = tgt
                continue
            if op == 28 and tgt is not None:   # GoToIf: follow both
                todo.append((tgt, n))
            pc = nxt
    return list(dict.fromkeys(cost))


def extract_tutors(ctx):
    tutors = []
    for f, d in ctx.S.items():
        ins = d['ins']
        sets = [x for x in d['recs'] if x['kind'] == 'set_move']
        if not sets:
            continue
        has = [x for x in d['recs'] if x['kind'] == 'has_move']
        spvars = {a[1] for (op, a, n, t) in ins.values() if op == 354}
        chains = [c for c in species_chains(ins) if c['var'] in spvars]
        compared = any(op == 17 and a[0] in spvars for (op, a, n, t) in ins.values())
        calls = {t: pc for pc, (op, a, n, t) in ins.items() if op in (26, 29)}
        chain_move = {}
        for ch in chains:
            caller = calls.get(ch['start'], ch['start'])
            prev = [h for h in has if h['pc'] < caller and h['args'][1] is not None]
            if prev:
                chain_move.setdefault(max(prev, key=lambda h: h['pc'])['args'][1], []).append(ch)
        moves = collections.OrderedDict()
        for x in sorted(sets, key=lambda r: r['pc']):
            m = x['args'][2]
            if m is None or m == 0:
                continue
            moves.setdefault(m, []).append(x['pc'])
        for m, pcs in moves.items():
            chs = chain_move.get(m)
            if chs:
                spset = set()
                for ch in chs:
                    spset |= set(ch['species'])
            else:
                spset = 'restricted' if compared else None
            # payment: cost instructions between the previous different-move set/has and this move's last set
            def mv_of(r):
                return r['args'][2] if r['kind'] == 'set_move' else r['args'][1]
            others = [r['pc'] for r in sets + has if mv_of(r) not in (m, None)]
            start = max([o for o in others if o < min(pcs)], default=0)
            end = min([o for o in others if o > max(pcs)], default=1 << 30)
            owner = reach_owner(d)
            cost = cost_of(ctx, d, owner, pcs, start, end)
            if not cost:
                other_moves = {mv_of(r) for r in sets + has} - {m, None}
                cost = cost_after(ctx, d, pcs, other_moves)
            ents = set().union(*(owner.get(pc, set()) for pc in pcs))
            picks = any(op in (349, 351, 353, 653) and owner.get(pc, set()) & ents for pc, (op, a, n, t) in ins.items())
            trade = any(op == 470 and owner.get(pc, set()) & ents for pc, (op, a, n, t) in ins.items())
            kind = 'trade' if trade else ('tutor' if (picks or spset) else 'event')
            tutors.append(dict(file=f, move=m, species=spset, cost=cost, place=ctx.place_str(f), kind=kind))
    return tutors


def relearners(ctx):
    out = []
    for f, d in ctx.S.items():
        for r in d['recs']:
            if r['kind'] in ('relearner', 'tutor_init'):
                cost = cost_of(ctx, d, reach_owner(d), [r['pc']], 0, 1 << 30)
                out.append(dict(file=f, kind=r['kind'], place=ctx.place_str(f), cost=list(dict.fromkeys(cost))))
    return out


