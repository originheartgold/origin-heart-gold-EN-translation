def mart_calls(ctx):
    """[(file, 'special', list id) | (file, 'badge', None)]: the commands that really open a shop.
    Std file 3 holds the std scripts themselves (SpecialMartBuy/MartBuy on a variable), so its own
    commands are not call sites."""
    out = []
    for f, d in ctx.S.items():
        if f == ctx.std_file:
            continue
        for r in d['recs']:
            if r['kind'] == 'callstd' and r['args'][0] == MART_STD_SPECIAL and r['v8004'] is not None:
                out.append((f, 'special', r['v8004']))
            elif r['kind'] == 'callstd' and r['args'][0] in MART_STD_BADGE:
                out.append((f, 'badge', None))
            elif r['kind'] == 'special_mart' and r['args'][0] is not None:
                out.append((f, 'special', r['args'][0]))
            elif r['kind'] == 'mart':
                out.append((f, 'badge', None))
    return out


