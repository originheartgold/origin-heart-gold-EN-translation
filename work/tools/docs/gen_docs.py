def find_names(text, idx):
    """Longest-first non-overlapping matches of zh names in text."""
    hits, taken = [], [False] * len(text)
    for name in sorted(idx, key=len, reverse=True):
        start = 0
        while True:
            k = text.find(name, start)
            if k < 0:
                break
            if not any(taken[k:k + len(name)]):
                hits.append((k, idx[name]))
                for j in range(k, k + len(name)):
                    taken[j] = True
            start = k + 1
    return [i for _, i in sorted(hits)]


