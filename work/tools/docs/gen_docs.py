    for path, text in sorted(outputs.items()):
        old = None
        if os.path.exists(path):
            with open(path, encoding='utf-8') as fh:
                old = fh.read()
        if old != text:
            changed.append(path)
            if not a.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                tmp = path + '.tmp'
                with open(tmp, 'w', encoding='utf-8') as fh:
                    fh.write(text)
                os.replace(tmp, path)
    if a.findings_json:
        with open(a.findings_json, 'w', encoding='utf-8') as fh:
            json.dump([dict(title=t, text=x, refs=r) for t, x, r in findings], fh, ensure_ascii=False, indent=1)
    for p in changed:
        print(('would change: ' if a.check else 'wrote: ') + os.path.relpath(p, R.REPO))
    print('%d pages, %d changed' % (len(outputs), len(changed)))
    return 1 if (a.check and changed) else 0


