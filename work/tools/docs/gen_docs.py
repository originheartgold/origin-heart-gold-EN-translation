def _jumpers(d):
    if '_jumpers' not in d:
        j = {}
        for pc, (op, a, n, t) in d['ins'].items():
            if t is not None:
                j.setdefault(t, []).append(pc)
        d['_jumpers'] = j
    return d['_jumpers']


def var_writer(d, pc, var, depth=0):
    """The nearest command before pc that writes var: (pc, op, args), following CopyVar.
    Walks linear predecessors, then a single jump source; None if the path forks or nothing is found."""
    ins = d['ins']
    prev = d.setdefault('_prev', prev_map(ins))
    jumpers = _jumpers(d)
    cur, seen = pc, set()
    for _ in range(200):
        p = prev.get(cur)
        if p is not None and p in ins and not (ins[p][0] in R.TERM or (ins[p][0] in R.JUMPS and R.JUMPS[ins[p][0]])):
            cur = p
        else:
            js = jumpers.get(cur, [])
            if len(js) > 1 and depth < 4:       # several jumps in: fine when every way in has the same writer
                ws = [var_writer(d, j, var, depth + 1) for j in js]
                if all(w is not None for w in ws) and len({(w[1], tuple(w[2])) for w in ws}) == 1:
                    return ws[0]
                return None
            if len(js) != 1:
                return None
            cur = js[0]
        if cur in seen:
            return None
        seen.add(cur)
        op, a, n, t = ins[cur]
        if var not in a or op in (17, 18, 26, 28) or R.cmds()[op][0].startswith('Buffer'):
            continue
        if op in (42, 43) and a[0] == var and a[1] >= 0x4000 and depth < 4:     # CopyVar / SetOrCopyVar from a var
            return var_writer(d, cur, a[1], depth + 1)
        return cur, op, a
    return None


def _msg_bank(ctx, f):
    cache = ctx.__dict__.setdefault('_cond_msgs', {})
    if f not in cache:
        banks = sorted({ctx.zones[z]['msg_bank'] for z in ctx.file_zones.get(f, [])})
        if not banks:
            banks = [mb for _lo, sb, mb in ctx.rom.std_mapping() if sb == f]
        cache[f] = R.load_bank(banks[0]) if len(banks) == 1 else None    # None: several maps, several banks
    return cache[f]


def _menu_options(ctx, f, d, mpc):
    """{value: option text} of the MenuItemAdd lines after a MenuInit."""
    ins, pc, opts = d['ins'], d['ins'][mpc][2], {}
    for _ in range(40):
        if pc not in ins or ins[pc][0] == 752:     # MenuExec
            break
        if ins[pc][0] == 751:                      # MenuItemAdd [msg, 255, value]
            opts[ins[pc][1][2]] = ins[pc][1][0]
        pc = ins[pc][2]
    msgs = _msg_bank(ctx, f) or {}
    return {v: re.sub(r'\s+', ' ', re.sub(r'\{[^}]*\}', ' ', msgs.get(m, ''))).strip() for v, m in opts.items()}


def _plural(name, n):
    if n == 1:
        return 'the ' + name
    return '%d %s' % (n, name[:-1] + 'ies' if re.search(r'[^aeiou]y$', name) else name + 's')


def describe_condition(ctx, f, d, cpc, cmp, value, structured=False):
    """Player-readable form of 'var <cmp> value' at the compare in cpc. None = no restriction worth showing
    (accepting a battle, where you stand); BRANCH_ONLY when it can't be put in player terms."""
    w = var_writer(d, cpc, d['ins'][cpc][1][0])
    if w is None or cmp not in COND:
        return BRANCH_ONLY
    wpc, op, a = w
    eq, ne = cmp == 1, cmp == 5
    if op == 749 or (op == 750 and _msg_bank(ctx, f) is None):   # options from a shared message bank
        return ANSWER_ONLY
    if op == 750 and any(len(t) > 50 for t in _menu_options(ctx, f, d, wpc).values()):
        return ANSWER_ONLY                        # dialogue lines, not option labels: the map's message bank doesn't fit
    if op == 750 and (eq or ne):                  # MenuInit … MenuExec: a menu of options
        opt = _menu_options(ctx, f, d, wpc).get(value)
        if opt and structured:                    # combined per menu in conditions_for
            return ('menu', wpc, eq, value)
        if opt:
            return ('if you pick “%s”' if eq else 'unless you pick “%s”') % opt
        return BRANCH_ONLY
    if op in (748, 63) and (eq or ne) and value in (0, 1):   # Yes/No (0 = Yes)
        yes = (value == 0) == eq
        return None if yes else 'if you answer “No”'
    if op in (105, 386):                          # player coordinates / facing: only the approach differs
        return None
    if op == 206 and (eq or ne) and value > 2:    # starter species
        if STARTER_NEVER_SET:
            return None if ne else NEVER + (': the game checks for a %s starter, but this hack never records '
                                             'which starter you chose (not confirmed in game)') % ctx.sp(value)
        return ('if your starter was %s' if eq else 'if your starter wasn\'t %s') % ctx.sp(value)
    if op == 281 and (eq or ne) and value in (0, 1):
        return 'for boy players' if (value == 0) == eq else 'for girl players'
    if op == 294 and a[0] < len(BADGE_NAMES) and (eq or ne) and value in (0, 1):
        has = (value == 1) == eq
        return ('once you have the %s Badge' if has else 'before you have the %s Badge') % BADGE_NAMES[a[0]]
    if op == 296 and cmp in CMP_WORDS:
        return 'with %s %d Badges' % (CMP_WORDS[cmp], value)
    if op == 484 and value < 7 and (eq or ne):
        return ('on %ss' if eq else 'except on %ss') % WEEKDAYS[value]
    if op == 128 and a[0] < 0x4000 and a[1] < 0x4000 and (eq or ne) and value in (0, 1):
        has = (value == 1) == eq
        return ('if you have %s' if has else 'if you don\'t have %s') % (
            ('at least ' if a[1] > 1 else '') + _plural(ctx.it(a[0]), max(a[1], 1)))
    if op in (332, 356) and cmp in CMP_WORDS:
        return 'with %s %d Pokémon in your party' % (CMP_WORDS[cmp], value)
    return BRANCH_ONLY



def block_start(d, pc, prev):
    ins = d['ins']
    targets = d.setdefault('_targets', set(t for (_, _, _, t) in ins.values() if t is not None) | set(d['entries']))
    while pc not in targets and pc in prev and prev[pc] in ins:
        op = ins[prev[pc]][0]
        if op in R.TERM or (op in R.JUMPS and R.JUMPS[op]):
            break
        pc = prev[pc]
    return pc


def _cond_paths(ctx, f, d, pc, depth):
    """The ways into pc, each a list of AND-ed conditions (nearest first). Tests the battle passes by not
    jumping count only when they can be put in words; story checks above the nearest one are left out."""
    ins, prev = d['ins'], d['_prev']
    b = block_start(d, pc, prev)
    parts, cur = [], pc
    while cur != b and prev.get(cur) in ins:
        p = prev[cur]
        if ins[p][0] == 28 and prev.get(p) in ins and ins[prev[p]][0] == 17:
            dsc = describe_condition(ctx, f, d, prev[p], NEG_CMP.get(ins[p][1][0]), ins[prev[p]][1][1], True)
            if dsc is not None and dsc != BRANCH_ONLY:
                parts.append(dsc)
        cur = p
    if depth >= 6:
        return [parts]
    ways = [(j, op, a[0]) for j, (op, a, n, t) in ins.items() if t == b and op in (22, 28)]    # GoTo / GoToIf into b
    p = prev.get(b)
    if p in ins and not (ins[p][0] in R.TERM or (ins[p][0] in R.JUMPS and R.JUMPS[ins[p][0]])):
        ways.append((p, None, None))                                                            # the line above
    alts = []
    for j, op, cmp in ways:
        if op is None and ins[j][0] == 28:          # a test not taken just above b
            op, cmp = 28, NEG_CMP.get(ins[j][1][0])
        dsc = None
        if op == 28:
            c = prev.get(j)
            dsc = describe_condition(ctx, f, d, c, cmp, ins[c][1][1], True) if c in ins and ins[c][0] == 17 else BRANCH_ONLY
            if dsc == BRANCH_ONLY and depth > 0:
                dsc = None
        for sub in _cond_paths(ctx, f, d, j, depth + 1):
            alts.append(parts + ([dsc] if dsc else []) + sub)
        if len(alts) > 8:
            break
    return alts or [parts]


def _render_path(ctx, f, d, parts):
    """One way in as text. Only the last menu or Yes/No answer before the battle is kept (earlier answers
    and retry loops would only add noise); other conditions are kept once. None if the tests contradict."""
    menu_pc = next((x[1] for x in parts if isinstance(x, tuple)), None)
    pick = None
    for x in parts:                                  # nearest first
        if isinstance(x, tuple) or x == 'if you answer “No”':
            if pick is None and not isinstance(x, tuple):
                pick = x
            elif pick is None:
                pick = ('menu', menu_pc)
    allowed = None
    if isinstance(pick, tuple):
        opts = _menu_options(ctx, f, d, menu_pc)
        allowed = set(opts)
        for x in parts:
            if isinstance(x, tuple) and x[1] == menu_pc:
                allowed = allowed & {x[3]} if x[2] else allowed - {x[3]}
        names = [opts[v] for v in sorted(allowed) if opts.get(v)]
        if not names:
            return None
        pick = 'if you pick ' + ' or '.join('“%s”' % n for n in names)
    text = list(dict.fromkeys(x for x in reversed(parts) if isinstance(x, str) and x != 'if you answer “No”'))
    never = [x for x in text if x.startswith(NEVER)]
    if never:
        return [never[0]]
    if 'for boy players' in text and 'for girl players' in text:
        return None                                  # contradicting tests: no real path
    for x in text:
        if x.startswith('before you have the ') and 'once you have the ' + x[len('before you have the '):] in text:
            return None
    return [x for x in text if x != BRANCH_ONLY] + ([pick] if pick else []) + ([BRANCH_ONLY] if BRANCH_ONLY in text else [])


def _complement(x):
    for a, b in (('for boy players', 'for girl players'), ('if you have ', 'if you don\'t have '),
                 ('before you have the ', 'once you have the ')):
        if x.startswith(a):
            return b + x[len(a):] if a.endswith(' ') else b
        if x.startswith(b):
            return a + x[len(b):] if b.endswith(' ') else a
    return None


def conditions_for(d, pc, ctx=None, f=None):
    """Player-readable conditions of the paths that lead to pc: alternatives ('or'), each a ', '-joined list
    of conditions that all hold. [] = no restriction worth showing; [BRANCH_ONLY] when a way in depends on
    something that can't be put in player terms (story flags, story progress vars)."""
    if ctx is None:
        return []
    d.setdefault('_prev', prev_map(d['ins']))
    alts = []
    for parts in _cond_paths(ctx, f, d, pc, 0):
        a = _render_path(ctx, f, d, parts)
        if a is not None and a not in alts:
            alts.append(a)
    merged = True
    while merged:                                    # "boy … or girl …" with the rest equal → the rest
        merged = False
        for i, a in enumerate(alts):
            for j, b in enumerate(alts):
                diff = [x for x in a if x not in b]
                if j > i and len(a) == len(b) and len(diff) == 1 and _complement(diff[0]) in b:
                    alts[i] = [x for x in a if x != diff[0]]
                    del alts[j]
                    merged = True
                    break
            if merged:
                break
    if [] in alts:                                   # one way in has no restriction worth showing
        return []
    alts = [a for a in alts if not any(b != a and set(b) < set(a) for b in alts)]   # "X" covers "X, Y"
    groups = {}                                      # same conditions, different menu options → one line
    for a in alts:
        picks = [x for x in a if x.startswith('if you pick ')]
        rest = tuple(x for x in a if not x.startswith('if you pick '))
        groups.setdefault(rest, []).extend(p[len('if you pick '):] for p in picks[:1])
    alts = []
    for rest, picks in groups.items():
        names = list(dict.fromkeys(n for p in picks for n in p.split(' or ')))
        pick = ['if you pick ' + (', '.join(names[:-1]) + ' or ' + names[-1] if len(names) > 1 else names[0])] if names else []
        a = list(rest)
        a[len([x for x in a if x != BRANCH_ONLY]):len([x for x in a if x != BRANCH_ONLY])] = pick
        alts.append(a)
    alts = list(dict.fromkeys(', '.join(a) for a in alts))
    if BRANCH_ONLY in alts:
        return [BRANCH_ONLY]
    if len(alts) > 1 and any(not a.startswith(NEVER) for a in alts):
        alts = [a for a in alts if not a.startswith(NEVER)]
    return alts


