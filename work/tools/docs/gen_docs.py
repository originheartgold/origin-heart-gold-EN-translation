def evo_conds(ctx, m, p):
    """Structured conditions for the site: [{text, item|move|species: id}]; empty for a method the game never checks."""
    out = []
    for c in EVO_CONDS.get(m, []):
        if isinstance(c, tuple):
            out.append({'text': c[0], c[1]: p})
        else:
            out.append({'text': c.format(p=p)})
    return out


def evo_official(m, p):
    """What the official games need, for a method this game never checks."""
    return NEVER_EVO.get(m, 'method %d' % m).format(p=p)


def evo_notes(ctx, sp):
    """Player notes for one species' evolutions: which slot wins when two level-up branches match."""
    out = []
    ev = [(m, p, evo_target(ctx, sp, t)) for m, p, t in ctx.evos[sp]]
    for i, (m, p, t) in enumerate(ev):
        later = [(m2, p2, t2) for m2, p2, t2 in ev[i + 1:] if m2 in LEVEL_UP_EVO and t2 != t]
        if m == 4:
            for m2, p2, t2 in later:
                if m2 not in (4, 13, 22, 23):
                    out.append('The level check comes first: evolve it into %s before Lv %d, or it becomes %s.' % (
                        ctx.sp(t2), p, ctx.sp(t)))
        elif m == 27:
            hit = list(dict.fromkeys(ctx.sp(t2) for m2, _, t2 in later if m2 in (1, 2, 3, 18, 19, 37)))
            if hit:
                out.append('If it knows a Fairy-type move and has friendship 158 or more, it becomes %s, not %s.' % (
                    ctx.sp(t), ', '.join(hit[:-1]) + ' or ' + hit[-1] if len(hit) > 1 else hit[0]))
        elif m == 2:
            for m2, p2, t2 in later:
                if m2 == 18:
                    out.append('With high friendship it becomes %s during the day even while holding %s: evolve it '
                               'into %s before its friendship gets high.' % (ctx.sp(t), ctx.it(p2), ctx.sp(t2)))
    return out


def evo_target(ctx, s, t):
    """Evolution target as a species index: a form evolves into the same form of the target when the
    target has that form (Alolan Vulpix -> Alolan Ninetales), else into the target itself."""
    if s in ctx.forms and t not in ctx.forms:
        return form_index(ctx, t, ctx.forms[s][1])
    return t


def evo_parents(ctx):
    par = collections.defaultdict(list)
    for s, ev in enumerate(ctx.evos):
        for m, p, t in ev:
            par[evo_target(ctx, s, t)].append((s, m, p))
    return par


def tutor_compat_for(ctx, tutors, sp):
    base = ctx.forms[sp][0] if sp in ctx.forms else sp
    out = []
    for t in tutors:
        if t.get('kind', 'tutor') != 'tutor':
            continue
        if t['species'] == 'restricted':
            continue
        if t['species'] is None or base in t['species']:
            out.append(t['move'])
    return sorted(set(out), key=ctx.mv)


