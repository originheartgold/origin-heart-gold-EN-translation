def check_trainers(ctx, tds, parties):
    issues = []
    for tid, (td, mons) in enumerate(zip(tds, parties)):
        if tid == 0 or not mons:
            continue
        for m in mons:
            sp, name = m['species'], ctx.sp(m['species'], m['form'])
            where = 'trainer #%d %s %s: %s' % (tid, ctx.TRC.get(td['cls'], ''), ctx.TRN.get(tid, ''), name)
            if not (1 <= sp < 1441) or not sum(ctx.personal[sp]['stats']):
                issues.append((where, 'invalid species %d' % sp))
                continue
            for mv in m['moves']:
                if mv >= len(ctx.moves):
                    issues.append((where, 'invalid move id %d' % mv))
            if len(set(m['moves'])) != len(m['moves']):
                issues.append((where, 'duplicate move in moveset: %s' % ', '.join(ctx.mv(x) for x in m['moves'])))
            if m['level'] > 100 or m['level'] == 0:
                issues.append((where, 'level %d' % m['level']))
            if m['item'] >= len(ctx.items):
                issues.append((where, 'invalid item %d' % m['item']))
            idx = sp
            if m['form']:
                for tgt, (b, f) in ctx.forms.items():
                    if b == sp and f == m['form']:
                        idx = tgt
            p = ctx.personal[idx]
            legal = set(p['abilities']) | {p['hidden_ability']}
            if m['ability'] and m['ability'] not in legal:
                issues.append((where, 'ability %s is not one of its abilities (%s)' % (
                    ctx.ab(m['ability']), ' / '.join(ctx.ab(a) for a in legal if a))))
    return issues


