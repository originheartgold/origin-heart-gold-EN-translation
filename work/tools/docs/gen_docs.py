def item_ball_table(ctx):
    """file 141 entry i (script 7000+i) -> (item, qty)."""
    f = next(sb for lo, sb, mb in ctx.rom.std_mapping() if lo == 7000)
    d = ctx.S[f]
    R.const_prop(d['entries'], d['ins'])
    out = {}
    for i, e in enumerate(d['entries']):
        pc, item, qty = e, None, 1
        for _ in range(4):
            if pc not in d['ins']:
                break
            op, a, n, t = d['ins'][pc]
            if op == 41 and a[0] == 0x8008:
                item = a[1]
            if op == 41 and a[0] == 0x8009:
                qty = a[1]
            pc = n
        if item:
            out[7000 + i] = (item, qty)
    return out


ITEM_BALL_SPRITE = 87


def local_gifts(ctx, f, entry_no):
    """Item gifts reachable from local script entry_no (1-based) of script file f."""
    d = ctx.S.get(f)
    if not d or not (1 <= entry_no <= len(d['entries'])):
        return []
    owner = d.setdefault('_owner', reach_owner(d))
    out = []
    for r in d['recs']:
        if entry_no - 1 not in owner.get(r['pc'], ()):
            continue
        if r['kind'] == 'item_give' and r['args'][0]:
            out.append((r['pc'], r['args'][0], r['args'][1] or 1))
        elif r['kind'] == 'callstd' and r['args'][0] in GIVE_STDS and r['v8004']:
            out.append((r['pc'], r['v8004'], r['v8005'] or 1))
    return out


def field_items(ctx):
    """zone -> dict(ball=[(item, qty)], hidden=[(item, qty)]). Also records the script sites of
    item balls that use a local script, so the gift list can leave them out."""
    if getattr(ctx, '_field_cache', None) is not None:
        return ctx._field_cache
    balls = item_ball_table(ctx)
    hidden = {h['index']: h for h in ctx.rom.hidden_items()}
    res = collections.defaultdict(lambda: dict(ball=[], hidden=[]))
    pos = collections.defaultdict(lambda: dict(ball=[], hidden=[]))   # same order as res: (x, z) on the map
    ctx.field_pos = pos
    ctx.ball_sites = set()
    seen_ev = set()
    for z in sorted(ctx.zones, key=lambda z: ctx.zrank(z['zone_id'])):
        b = z['events_bank']
        if b in seen_ev:
            continue
        seen_ev.add(b)
        ev = ctx.events.get(b)
        if not ev:
            continue
        f = z['scripts_bank']
        for o in ev['obj']:
            if o['script'] in balls:
                res[z['zone_id']]['ball'].append(balls[o['script']])
                pos[z['zone_id']]['ball'].append((o['x'], o['z']))
            elif o['sprite'] == ITEM_BALL_SPRITE and 0 < o['script'] < 1000:
                for pc, it, q in local_gifts(ctx, f, o['script']):
                    res[z['zone_id']]['ball'].append((it, q))
                    pos[z['zone_id']]['ball'].append((o['x'], o['z']))
                    ctx.ball_sites.add((f, pc))
        for g in ev['bg']:
            if 8000 <= g['script'] < 8800:
                h = hidden.get(g['script'] - 8000)
                if h:
                    res[z['zone_id']]['hidden'].append((h['item'], h['qty']))
                    pos[z['zone_id']]['hidden'].append((g['x'], g['z']))
            elif g['type'] == 2 and 0 < g['script'] < 1000:
                for pc, it, q in local_gifts(ctx, f, g['script']):
                    res[z['zone_id']]['hidden'].append((it, q))
                    pos[z['zone_id']]['hidden'].append((g['x'], g['z']))
                    ctx.ball_sites.add((f, pc))
    ctx._field_cache = res
    return res


GIVE_STDS = {2033: 'gift', 2008: 'gift'}


def script_gifts(ctx):
    """[(file, pc, item, qty, conds, how)] from GiveItem and the give-item std scripts."""
    out = []
    for f, d in ctx.S.items():
        owner = None
        for r in d['recs']:
            item = qty = None
            alts = []
            if r['kind'] == 'item_give':
                item, qty = r['args'][0], r['args'][1]
                alts = r.get('alt0') or []
            elif r['kind'] == 'callstd' and r['args'][0] in GIVE_STDS:
                item, qty = r['v8004'], r['v8005']
                alts = r.get('alt8004') or []
            else:
                continue
            if (f, r['pc']) in getattr(ctx, 'ball_sites', ()):
                continue
            if f == ctx.ball_file:
                # the item-ball std script's shared GiveItem(0x8004): not a source of its own
                # (item balls are listed per map by field_items)
                continue
            if not item and not alts:
                continue
            if owner is None:
                owner = reach_owner(d) if 'ins' in d else {}
            if not item:
                # a menu, a draw or several branches choose the item: list each possible one as a prize or
                # choice (never as a purchase), with what the same entry path can take from you
                ents = owner.get(r['pc'], set())
                cp = []
                for x in d['recs']:
                    if not (owner.get(x['pc'], set()) & ents):
                        continue
                    if x['kind'] == 'money_take' and x['args'][0]:
                        cp.append('₽%d' % x['args'][0])
                    elif x['kind'] == 'coins_take' and x['args'][0]:
                        cp.append('%d coins' % x['args'][0])
                    elif x['kind'] == 'bp_check':
                        cp.append('BP')
                cp = list(dict.fromkeys(cp))
                for it in alts:
                    if 0 < it < len(ctx.items):
                        out.append(dict(file=f, pc=r['pc'], item=it, qty=qty or 1, pay=[], choice=True, choice_pay=cp))
                continue
            # price paid on the same entry path just before (shops by script, prize counters).
            # Prefer payments after the previous give, so a vendor with one branch per item is
            # not charged the previous branch's price too; a bundle (one payment, several gives
            # in a row) falls back to the payment before the first give.
            prev_give = max((x['pc'] for x in d['recs'] if x['pc'] < r['pc'] and (
                x['kind'] == 'item_give' or (x['kind'] == 'callstd' and x['args'][0] in GIVE_STDS))), default=-1)

            def payments(lo):
                pay = []
                for x in d['recs']:
                    if lo < x['pc'] < r['pc'] and r['pc'] - x['pc'] < 120 and owner.get(x['pc'], set()) & owner.get(r['pc'], set()):
                        if x['kind'] == 'coins_take' and x['args'][0]:
                            pay.append('%d coins' % x['args'][0])
                        elif x['kind'] == 'money_take' and x['args'][0]:
                            pay.append('₽%d' % x['args'][0])
                        elif x['kind'] == 'item_take' and x['args'][0] and x['args'][0] != item:
                            pay.append('%s ×%s' % (ctx.it(x['args'][0]), x['args'][1]))
                return pay
            pay = payments(prev_give) or payments(-1)
            out.append(dict(file=f, pc=r['pc'], item=item, qty=qty or 1, pay=pay))
    return out


def gift_pay_text(g):
    """What a script source costs, in player words: a price, or for a menu/draw choice what that path takes."""
    if g.get('choice'):
        cp = g.get('choice_pay') or []
        if not cp:
            return 'one of several; chosen in a menu or by a draw'
        return 'one of several; paid with ' + (' or '.join(cp) if len(cp) < 3 else ', '.join(cp[:-1]) + ' or ' + cp[-1]) + (
            ' depending on the choice' if len(cp) > 1 else '')
    return ', '.join(g['pay'])


