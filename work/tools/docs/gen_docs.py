def species_block(ctx, sp, par, tutors, avail):
    p = ctx.personal[sp]
    st = R.personal_stats(p)
    t1, t2 = p['types']
    types = ctx.ty(t1) + ('' if t2 == t1 else ' / ' + ctx.ty(t2))
    abil = [ctx.ab(a) for a in p['abilities'] if a]
    abil = list(dict.fromkeys(abil))
    ha = ctx.ab(p['hidden_ability']) if p['hidden_ability'] else '—'
    L = ['### #%04d %s' % (sp, md_escape(ctx.sp(sp))), '']
    L.append('| Type | Abilities | Hidden ability | HP | Atk | Def | SpA | SpD | Spe | Total |')
    L.append('|---|---|---|---|---|---|---|---|---|---|')
    L.append('| %s | %s | %s | %s | %d |' % (types, ' / '.join(abil) or '—', ha, ' | '.join(map(str, st)), sum(st)))
    L.append('')
    eg = [R.EGG_GROUPS.get(g, str(g)) for g in p['egg_groups']]
    eg = list(dict.fromkeys(eg))
    evs = p['ev_yield']
    evtxt = ', '.join('%d %s' % (v, n) for v, n in zip([evs[0], evs[1], evs[2], evs[4], evs[5], evs[3]],
                                                       ['HP', 'Atk', 'Def', 'SpA', 'SpD', 'Spe']) if v)
    held = [ctx.it(i) for i in p['items'] if i]
    L.append('Catch rate %d · %s · egg groups %s · %s growth · EV yield %s%s  ' % (
        p['catch_rate'], gender_text(p['gender']), ' / '.join(eg), R.GROWTH[p['growth']] if p['growth'] < 6 else '?',
        evtxt or '—', (' · wild held item: ' + ', '.join(held)) if held else ''))
    def how(m, q):
        if evo_possible(m) and not evo_works(m, q):
            return '%s; not possible: %s can\'t be obtained' % (evo_text(ctx, m, q), ctx.it(q))
        return evo_text(ctx, m, q)
    ev_from = ['%s (%s)' % (ctx.sp(s), how(m, q)) for s, m, q in par.get(sp, [])]
    ev_to = ['%s (%s)' % (ctx.sp(evo_target(ctx, sp, t)), how(m, q)) for m, q, t in ctx.evos[sp]]
    ev_to = list(dict.fromkeys(ev_to))
    ev_from = list(dict.fromkeys(ev_from))
    if ev_from:
        L.append('Evolves from: ' + '; '.join(ev_from) + '  ')
    if ev_to:
        L.append('Evolves into: ' + '; '.join(ev_to) + '  ')
        for n in evo_notes(ctx, sp):
            L.append(n + '  ')
    if not ev_from and not ev_to:
        L.append('Does not evolve.  ')
