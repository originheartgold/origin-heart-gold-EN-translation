    case['expected_sizes']=expected_sizes;case['observed_sizes']=observed_sizes
    case['status']=('expected-failure' if pr.corrupt else 'negative-control-missed') if ref.startswith('negative-') else ('fail' if failure else ('pass' if all(case['assertions'].values()) else 'incomplete'))
    e.destroy();(a.out/'current-result.json').write_text(json.dumps(case,indent=2))
    return 0
