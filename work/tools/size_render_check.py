#!/usr/bin/env python3
"""Local-only SIZE renderer harness; never edits source banks or production ROM.

Injects exact candidate text into trainer dialogue 0718#160 in an isolated ROM.
This exercises the real field printer, not original story scripts or UI contexts.
Use the inventory generated by size inventory audit. Native UI cases are excluded.
Each case starts at the same pre-dialogue save state. Heap checks run every 10
frames; all pages and a following normal-font sentinel are captured. Broken
Misty newline is an expected-failure negative control. Outputs contain game text
and MUST remain under ignored work/build.
"""
import argparse, hashlib, json, re, subprocess, sys, struct
from pathlib import Path
import msgtool as m

SENTINEL = 'Normal text after shout.{NEWLINE}Second normal line.'
CAPACITY = 512

def case_text(text):
    # Preserve the original bytes, including trailing page controls. Add one
    # separate ordinary-font page without adding a size reset: catches leakage.
    boundary = '' if text.endswith(('{SCROLL}', '{CLEAR}')) else '{SCROLL}'
    return text + boundary + SENTINEL + '{SCROLL}'

def pages(text):
    return re.split(r'\{(?:SCROLL|CLEAR)\}', text.rstrip().removesuffix('{SCROLL}'))

def render_text(entry):
    if entry.get('ui_case'):
        return entry['en'] if entry['en'].endswith('{SCROLL}') else entry['en']+'{SCROLL}'
    return case_text(entry['en'])

def prepare_cases(entries, mode):
    """Carry native UI lifetime and font through maximum-name variants."""
    prepared=[]
    known_ui={f'a027/0302#{i}' for i in (2,26,31,*range(166,176))}
    for source in entries:
        entry=dict(source)
        if entry['ends_in_enlarged_size']:
            if entry['ref'] not in known_ui:
                raise ValueError('No verified native UI consumer for '+entry['ref'])
            label=int(entry['ref'].split('#')[1])>=166
            entry.update(ui_case=True,harness_font=4 if label else 1,native_width=144 if label else 216)
        prepared.append(entry)
    if mode=='ordinary':return [x for x in prepared if not x['ends_in_enlarged_size']]
    ui=[x for x in prepared if x['ends_in_enlarged_size']]
    names=[dict(x,source_ref=x['ref'],ref=x['ref']+'-max-name',en=x['en'].replace('{VAR:0103:0}','WWWWWWW'),substitution='literal seven widest W glyphs replacing player-name slot; formatter itself not exercised') for x in prepared if '{VAR:0103:0}' in x['en']]
    return ui+names

def identity(path):
    h=hashlib.sha256()
    with open(path,'rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):h.update(block)
    return {'path':str(path),'sha256':h.hexdigest()}

