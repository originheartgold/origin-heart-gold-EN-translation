    report={'schema_version':1,'scope':'injected native field-printer harness; not original story encounters or Pokéathlon screens','mode':a.mode,'limitations':['Base player-name slots are empty in this trainer fixture; literal seven-W variants check maximum geometry separately, not variable formatter execution.','UI cases select the statically verified native consumer font in the field-printer template. Native UI dimensions are compared independently; the fixture window remains216x32.'],'source':source_identity,'save':identity(a.save),'excluded_native_ui':excluded,'cases':[],'expected_refs':[x['ref'] for x in entries],'script':script_identity,'inventory':inventory_identity,'code_guards_passed':True,'inventory_matches_candidate':True}
    for entry in entries:
        text=render_text(entry);units=m.encode_text(text,cm)
        if len(units)>CAPACITY:raise ValueError('harness capacity exceeded')
        strings[160]=units+[0xffff]*(CAPACITY-len(units));encoded=m.encrypt_bank(seed,strings,trailer)
        assert len(encoded)==len(bank)
        with testrom.open('r+b') as f:f.seek(offset);f.write(encoded)
